export function generateCatalog() {
  const products = [];
  let id = 2001;

  CATEGORIES_LIST.forEach((categoryName, cIdx) => {
    const items = CATEGORY_CATALOG[categoryName] || [];
    items.slice(0, 15).forEach((item, idx) => {
      const code = categoryName.replace(/[^A-Za-z]/g, '').slice(0, 3).toUpperCase();
      products.push({
        id: id++,
        sku: `${code}-${String(cIdx + 1).padStart(2, '0')}-${String(idx + 1).padStart(2, '0')}`,
        name: item.name,
        brand: item.brand,
        categoryName,
        spec: item.spec,
        description: item.desc,
        rating: item.rating,
        reviews: item.reviews,
        sellingPrice: item.price,
        originalPrice: item.mrp,
        imageUrl: item.img,
        _isBackend: false,
      });
    });
  });

  return products;
}